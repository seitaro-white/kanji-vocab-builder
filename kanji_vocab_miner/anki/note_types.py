"""Stable vocabulary note schemas and card formats, without Anki I/O."""

from dataclasses import dataclass

# These are collection conventions, not runtime configuration.
VOCAB_DECK_NAME = "KanjiVocabMiner-Vocabulary"
LEGACY_VOCAB_NOTE_TYPE = "MyJapaneseVocabulary"
VOCAB_NOTE_TYPE_V2 = "MyJapaneseVocabularyV2"
VOCAB_NOTE_TYPE_V3 = "MyJapaneseVocabularyV3"
VOCAB_NOTE_TYPE = LEGACY_VOCAB_NOTE_TYPE
VOCAB_TAG = "kanji-vocab-miner"

FIELDS = {
    "front": "Front",
    "back": "Back",
    "expression": "Expression",
    "kana_reading": "Kana Reading",
    "grammar": "Grammar",
    "definition": "Definition",
    "additional_definitions": "Additional Definitions",
    "jlpt": "JLPT",
}
LEGACY_FIELDS = FIELDS
VOCAB_V2_FIELDS = {
    **LEGACY_FIELDS,
    "japanese_definition": "JapaneseDefinition",
    "japanese_cue": "JapaneseCue",
    "recall": "Recall",
    "definition_source": "DefinitionSource",
    "definition_url": "DefinitionURL",
}
VOCAB_V3_FIELDS = {
    **VOCAB_V2_FIELDS,
    "nuance": "Nuance",
    "example": "Example",
    "kanji_explanation": "KanjiExplanation",
}


@dataclass(frozen=True)
class CardTemplate:
    """An immutable front/back template pair that generates one Anki card.

    Attributes:
        name: Template name used when creating or refreshing the model.
        front_template: HTML with Anki field substitutions and conditionals.
        back_template: Answer-side HTML, not a rendered note's field content.
    """

    name: str
    front_template: str
    back_template: str


@dataclass(frozen=True)
class NoteTypeDefinition:
    """An immutable vocabulary note schema and its ordered card templates.

    This describes a model, not a vocabulary note or an AnkiConnect request.
    Model setup serializes it separately for creation and safe refresh.

    Attributes:
        model_name: Exact Anki model name, isolating legacy, V2 and V3 notes.
        field_names: Field names in the required Anki storage order.
        css: Shared stylesheet for every card generated by this model.
        templates: Card templates in generation order: Recognition, then Recall.
    """

    model_name: str
    field_names: tuple[str, ...]
    css: str
    templates: tuple[CardTemplate, ...]


def _note_type_css() -> str:
    """Return shared card styling, including the rt.known visibility contract."""
    return """
.card {
    font-family: ume-pms3, "Noto Sans CJK JP", sans-serif;
    font-size: 22px;
    text-align: center;
    color: black;
    background-color: #fcf7ef;
}

.japanese {
    font-size: 2em;
}

.english {
    font-size: 1.4em;
    margin: 2% 2%;
}

.smallEnglish {
    font-size: 0.6em;
    margin: 2% 2%;
}

ruby {
    ruby-align: center;
}

rt {
    font-size: 0.5em;
}

rt.known {
    display: none;
}

.show-all-furigana rt.known {
    display: ruby-text;
}
"""


def _v2_recognition_template() -> CardTemplate:
    """Return the established Japanese-to-English recognition card template."""
    return CardTemplate(
        name="Recognition",
        front_template='<div class="japanese">{{Front}}</div>',
        back_template=(
            '<div class="show-all-furigana">{{FrontSide}}</div>\n\n'
            "<hr id=answer>\n\n{{Back}}"
        ),
    )


def _v2_note_type_css() -> str:
    """Return shared furigana styling with Japanese-cue and source styles."""
    return _note_type_css() + """

.japanese-cue {
    font-size: 1.35em;
    line-height: 1.6;
}

.sense + .sense {
    margin-top: 0.75em;
}

.reading {
    margin-top: 0.4em;
}

.definition-source {
    font-size: 0.65em;
    margin-top: 1.2em;
}
"""


def _v2_recall_template() -> CardTemplate:
    """Return a Japanese-only recall template gated by the Recall field."""
    return CardTemplate(
        name="Recall",
        front_template=(
            '{{#Recall}}\n<div class="japanese-cue">'
            "{{JapaneseCue}}</div>\n{{/Recall}}"
        ),
        back_template=(
            '<div class="show-all-furigana japanese-cue">'
            "{{JapaneseCue}}</div>\n\n<hr id=answer>\n\n"
            '<div class="show-all-furigana japanese">{{Front}}</div>\n'
            '<div class="reading">{{Kana Reading}}</div>\n'
            '<div class="definition-source"><a href="{{DefinitionURL}}">'
            "{{DefinitionSource}}</a></div>"
        ),
    )


def _v3_recognition_template() -> CardTemplate:
    """Return recognition with optional enrichment sections on the answer."""
    return CardTemplate(
        name="Recognition",
        front_template=_v2_recognition_template().front_template,
        back_template=(
            '<div class="show-all-furigana">{{FrontSide}}</div>\n\n'
            '<hr id=answer>\n\n{{Back}}\n'
            '{{#Nuance}}<div class="enrichment-section">'
            '<div class="enrichment-label">Nuance</div>{{Nuance}}</div>{{/Nuance}}\n'
            '{{#Example}}<div class="enrichment-section">'
            '<div class="enrichment-label">Example</div>{{Example}}</div>{{/Example}}\n'
            '{{#KanjiExplanation}}<div class="enrichment-section">'
            '<div class="enrichment-label">Why these kanji</div>'
            '{{KanjiExplanation}}</div>{{/KanjiExplanation}}'
        ),
    )


def _v3_note_type_css() -> str:
    """Return V2 styling with enrichment sections and example highlighting."""
    return _v2_note_type_css() + """

.enrichment-section {
    margin-top: 1em;
    line-height: 1.5;
}

.enrichment-label {
    color: #777;
    font-size: 0.65em;
    font-weight: bold;
    margin-bottom: 0.25em;
    text-transform: uppercase;
}

.example-target {
    color: red;
    font-weight: bold;
}
"""


def vocab_note_type_v2() -> NoteTypeDefinition:
    """Describe the supported V2 model without constructing a wire payload.

    Returns:
        The immutable thirteen-field schema, styling and ordered card templates.
    """
    return NoteTypeDefinition(
        model_name=VOCAB_NOTE_TYPE_V2,
        field_names=tuple(VOCAB_V2_FIELDS.values()),
        css=_v2_note_type_css(),
        templates=(_v2_recognition_template(), _v2_recall_template()),
    )


def vocab_note_type_v3() -> NoteTypeDefinition:
    """Describe the current V3 model independently of older note types.

    Returns:
        The immutable V2-compatible schema with three additional enrichment
        fields, styling and ordered card templates.
    """
    return NoteTypeDefinition(
        model_name=VOCAB_NOTE_TYPE_V3,
        field_names=tuple(VOCAB_V3_FIELDS.values()),
        css=_v3_note_type_css(),
        templates=(_v3_recognition_template(), _v2_recall_template()),
    )
